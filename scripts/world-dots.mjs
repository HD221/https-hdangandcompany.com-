// Generates src/data/worldDots.ts: a dotted world map as one SVG path (equirectangular).
// Run with: node scripts/world-dots.mjs
import fs from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'

const require = createRequire(import.meta.url)
const topo = require('world-atlas/land-50m.json')
const land = feature(topo, topo.objects.land)

const STEP = 2.2 // degrees between dots
const LAT_TOP = 78
const LAT_BOTTOM = -56
const W = 720
const H = (LAT_TOP - LAT_BOTTOM) * (W / 360) // equirectangular: same scale both ways
const x = (lng) => ((lng + 180) / 360) * W
const y = (lat) => ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * H

let d = ''
let count = 0
for (let lat = LAT_TOP; lat >= LAT_BOTTOM; lat -= STEP) {
  for (let lng = -180 + STEP / 2; lng < 180; lng += STEP) {
    if (geoContains(land, [lng, lat])) {
      d += `M${x(lng).toFixed(1)} ${y(lat).toFixed(1)}h0`
      count++
    }
  }
}

const out = `// Generated by scripts/world-dots.mjs from Natural Earth land data (world-atlas). Do not edit by hand.
export const WORLD_W = ${W}
export const WORLD_H = ${H.toFixed(1)}
export const LAT_TOP = ${LAT_TOP}
export const LAT_BOTTOM = ${LAT_BOTTOM}
export const worldDots = '${d}'
`
fs.writeFileSync(new URL('../src/data/worldDots.ts', import.meta.url), out)
console.log('dots', count, 'bytes', out.length, 'height', H.toFixed(1))
